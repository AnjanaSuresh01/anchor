"""Emit the results table as markdown, generated from evals/results.jsonl.

The README's numbers are produced by this script rather than typed. A table
edited by hand drifts from the data it claims to report, and the drift is
invisible — this makes the published figures reproducible by anyone who clones
the repo and re-runs the sweep.

    python -m evals.report_markdown            # to stdout
    python -m evals.report_markdown --write    # splice into README.md
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

from evals.architectures import ARCHITECTURES
from evals.metrics import summarise

HERE = Path(__file__).parent
RESULTS = HERE / "results.jsonl"
README = HERE.parent / "README.md"

START = "<!-- RESULTS:START -->"
END = "<!-- RESULTS:END -->"


def rows() -> list[dict]:
    if not RESULTS.exists():
        return []
    return [
        json.loads(line)
        for line in RESULTS.read_text(encoding="utf-8").splitlines()
        if line.strip()
    ]


def fmt(v) -> str:
    if v is None:
        return "—"
    return f"{v:.3f}" if isinstance(v, float) else str(v)


def table(all_rows: list[dict]) -> str:
    lines = [
        "| | Architecture | n | recall@k | refusal acc | correct refusals "
        "| false refusals | unsupported cites | calls | p50 s |",
        "|---|---|---:|---:|---:|---:|---:|---:|---:|---:|",
    ]
    for key in sorted(ARCHITECTURES):
        name, _ = ARCHITECTURES[key]
        subset = [r for r in all_rows if r["architecture"] == key and not r.get("error")]
        if not subset:
            continue
        s = summarise(subset)
        lines.append(
            f"| **{key}** | `{name}` | {s['n']} | {fmt(s['recall@k'])} | "
            f"{fmt(s['refusal_accuracy'])} | {s['correct_refusals']} | "
            f"{s['false_refusals']} | {s['unsupported_citations']} | "
            f"{fmt(s['avg_calls'])} | {fmt(s['p50_seconds'])} |"
        )
    return "\n".join(lines)


def by_question_type(all_rows: list[dict]) -> str:
    """Per-type recall. The aggregate hides the thing Day 3 was built for:
    author questions are where the entity graph should show up, and they are
    only 4 of 50."""
    types = sorted({r["type"] for r in all_rows if not r.get("error")})
    header = "| Question type | n | " + " | ".join(
        f"{k} `{ARCHITECTURES[k][0]}`" for k in sorted(ARCHITECTURES)
    ) + " |"
    lines = [header, "|---|---:|" + "---:|" * len(ARCHITECTURES)]

    for t in types:
        cells = []
        counts = set()
        for key in sorted(ARCHITECTURES):
            subset = [
                r for r in all_rows
                if r["type"] == t and r["architecture"] == key and not r.get("error")
            ]
            if not subset:
                cells.append("—")
                continue
            counts.add(len(subset))
            s = summarise(subset)
            metric = s["recall@k"] if s["recall@k"] is not None else s["refusal_accuracy"]
            cells.append(fmt(metric))
        # Questions per architecture, carried in the table itself: a 0.286 ->
        # 0.964 swing means something different over 4 questions than over 40,
        # and a reader should not have to open the golden set to find out which.
        n = str(min(counts)) if len(counts) == 1 else (
            f"{min(counts)}–{max(counts)}" if counts else "—")
        lines.append(f"| `{t}` | {n} | " + " | ".join(cells) + " |")

    return "\n".join(lines)


def render(all_rows: list[dict]) -> str:
    if not all_rows:
        return "_No results yet. Run `python -m evals.run_eval`._"

    errors = [r for r in all_rows if r.get("error")]
    backend = "unknown"
    parts = [
        table(all_rows),
        "",
        "`recall@k` is measured only on questions with ground-truth ids. "
        "`refusal acc` is answering when answerable and refusing when not. "
        "`unsupported cites` counts citations to papers that were never retrieved.",
        "",
        "**Recall / refusal accuracy by question type** "
        "(recall where ground truth exists, refusal accuracy for unanswerables):",
        "",
        by_question_type(all_rows),
    ]
    if errors:
        parts += ["", f"_{len(errors)} run(s) errored and are excluded._"]
    parts += [
        "",
        f"_Generated by `python -m evals.report_markdown` from "
        f"{len(all_rows)} saved runs._",
    ]
    return "\n".join(parts)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--write", action="store_true", help="Splice into README.md")
    args = parser.parse_args()

    body = render(rows())
    if not args.write:
        print(body)
        return

    text = README.read_text(encoding="utf-8")
    if START not in text or END not in text:
        raise SystemExit(f"README.md is missing the {START} / {END} markers")

    before, _, rest = text.partition(START)
    _, _, after = rest.partition(END)
    README.write_text(f"{before}{START}\n{body}\n{END}{after}", encoding="utf-8")
    print(f"README.md updated ({len(rows())} runs)")


if __name__ == "__main__":
    main()
